# ── 保存到文件 ────────────────────────────────────

def save_corpus(base_dir: str | None = None):
    """将语料保存为 JSON 文件"""
    if base_dir is None:
        base_dir = str(CORPUS_DIR)
    data = build_corpus()
    for key, items in data.items():
        path = os.path.join(base_dir, key, "corpus.json")
        with open(path, "w", encoding="utf-8") as f:
            json.dump(items, f, ensure_ascii=False, indent=2)
        print(f"Saved {len(items)} texts to {path}")


if __name__ == "__main__":
    save_corpus()
